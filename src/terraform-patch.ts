const DEFAULT_LOG_RETENTION_DAYS = 30;

export function escapeHclString(value: string): string {
    return value
        .replace(/\\/g, "\\\\")
        .replace(/"/g, '\\"')
        .replace(/\n/g, "\\n")
        .replace(/\r/g, "\\r")
        .replace(/\t/g, "\\t");
}
export function generateFinopsPatch(findings, format, selectedIds?: string[]) {
    const picked = selectedIds && selectedIds.length > 0
        ? findings.filter((f) => selectedIds.includes(f.id))
        : findings;
    if (format === "cli") {
        return generateCliPatch(picked);
    }
    return generateTerraformPatch(picked);
}
function generateTerraformPatch(findings) {
    const blocks = [
        "# Generated by aws-bleed — review before apply",
        'terraform { required_version = ">= 1.5" }',
        "",
    ];
    const nats = findings.filter((f) => f.kind === "nat_missing_endpoints");
    const seenVpc = new Set();
    for (const f of nats) {
        const vpcId = String(f.evidence.vpcId);
        const region = f.region;
        if (seenVpc.has(vpcId))
            continue;
        seenVpc.add(vpcId);
        const missingS3 = f.evidence.missingS3Endpoint;
        const missingDdb = f.evidence.missingDynamoEndpoint;
        blocks.push(`# VPC ${vpcId} (${region}) — free gateway endpoints`);
        if (missingS3) {
            blocks.push(`resource "aws_vpc_endpoint" "s3_${sanitize(vpcId)}" {
  vpc_id       = "${escapeHclString(vpcId)}"
  service_name = "com.amazonaws.${escapeHclString(region)}.s3"
  route_table_ids = [] # attach your private route tables
}`);
        }
        if (missingDdb) {
            blocks.push(`resource "aws_vpc_endpoint" "dynamodb_${sanitize(vpcId)}" {
  vpc_id       = "${escapeHclString(vpcId)}"
  service_name = "com.amazonaws.${escapeHclString(region)}.dynamodb"
  route_table_ids = []
}`);
        }
        blocks.push("");
    }
    for (const f of findings.filter((x) => x.kind === "logs_infinite_retention")) {
        const name = String(f.evidence.logGroupName);
        blocks.push(`resource "aws_cloudwatch_log_group" "${sanitize(name)}" {
  name              = "${escapeHclString(name)}"
  retention_in_days = ${DEFAULT_LOG_RETENTION_DAYS}
}`);
        blocks.push("");
    }
    for (const f of findings.filter((x) => x.kind === "ebs_gp2")) {
        const vol = String(f.evidence.volumeId);
        blocks.push(`resource "aws_ebs_volume" "gp3_${sanitize(vol)}" {
  # Replace in-place: stop instance, snapshot, recreate as gp3, reattach
  availability_zone = "REPLACE_ME"
  size              = ${f.evidence.sizeGiB}
  type              = "gp3"
}`);
        blocks.push("");
    }
    for (const f of findings.filter((x) => x.kind === "ebs_available")) {
        blocks.push(`# Orphan volume ${f.evidence.volumeId} — snapshot then delete if unused`);
        blocks.push("");
    }
    for (const f of findings.filter((x) => x.kind === "eip_unassociated")) {
        blocks.push(`# Release idle EIP ${f.evidence.allocationId} (${f.evidence.publicIp})`);
        blocks.push("");
    }
    for (const f of findings.filter((x) => x.kind === "snapshot_stale")) {
        blocks.push(`# Stale snapshot ${f.evidence.snapshotId} — archive or delete after verify`);
        blocks.push("");
    }
    return blocks.join("\n").trimEnd() + "\n";
}
function generateCliPatch(findings) {
    const lines = ["#!/usr/bin/env bash", "set -euo pipefail", ""];
    for (const f of findings) {
        switch (f.kind) {
            case "nat_missing_endpoints":
                lines.push(`# aws ec2 create-vpc-endpoint --vpc-id ${f.evidence.vpcId} --service-name com.amazonaws.${f.region}.s3`);
                lines.push(`# aws ec2 create-vpc-endpoint --vpc-id ${f.evidence.vpcId} --service-name com.amazonaws.${f.region}.dynamodb`);
                break;
            case "logs_infinite_retention":
                lines.push(`aws logs put-retention-policy --log-group-name "${f.evidence.logGroupName}" --retention-in-days ${DEFAULT_LOG_RETENTION_DAYS}`);
                break;
            case "ebs_gp2":
                lines.push(`# migrate ${f.evidence.volumeId} gp2 -> gp3 via console or modify-volume`);
                break;
            case "eip_unassociated":
                lines.push(`aws ec2 release-address --allocation-id ${f.evidence.allocationId}`);
                break;
            default:
                lines.push(`# review finding ${f.id}`);
        }
    }
    return lines.join("\n") + "\n";
}
function sanitize(id) {
    return id.replace(/[^a-zA-Z0-9_]/g, "_").replace(/^(\d)/, "_$1");
}
