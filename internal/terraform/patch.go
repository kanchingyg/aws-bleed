package terraform

import (
	"fmt"
	"strings"

	"github.com/kanchingyg/aws-bleed/internal/scan"
)

const defaultLogRetentionDays = 30

// EscapeHclString escapes backslashes, quotes, and whitespace for HCL strings.
func EscapeHclString(value string) string {
	value = strings.ReplaceAll(value, "\\", "\\\\")
	value = strings.ReplaceAll(value, "\"", "\\\"")
	value = strings.ReplaceAll(value, "\n", "\\n")
	value = strings.ReplaceAll(value, "\r", "\\r")
	value = strings.ReplaceAll(value, "\t", "\\t")
	return value
}

// GenerateFinopsPatch emits Terraform or CLI remediation for findings.
func GenerateFinopsPatch(findings []scan.Finding, format string, selectedIDs []string) string {
	picked := findings
	if len(selectedIDs) > 0 {
		var filtered []scan.Finding
		idSet := make(map[string]bool, len(selectedIDs))
		for _, id := range selectedIDs {
			idSet[id] = true
		}
		for _, f := range findings {
			if idSet[f.ID] {
				filtered = append(filtered, f)
			}
		}
		picked = filtered
	}
	if format == "cli" {
		return generateCLIPatch(picked)
	}
	return generateTerraformPatch(picked)
}

func generateTerraformPatch(findings []scan.Finding) string {
	blocks := []string{
		"# Generated by aws-bleed — review before apply",
		"terraform { required_version = \">= 1.5\" }",
		"",
	}
	seenVpc := make(map[string]bool)
	for _, f := range findings {
		if f.Kind != "nat_missing_endpoints" {
			continue
		}
		vpcID := fmt.Sprint(f.Evidence["vpcId"])
		if seenVpc[vpcID] {
			continue
		}
		seenVpc[vpcID] = true
		missingS3, _ := f.Evidence["missingS3Endpoint"].(bool)
		missingDdb, _ := f.Evidence["missingDynamoEndpoint"].(bool)
		blocks = append(blocks, fmt.Sprintf("# VPC %s (%s) — free gateway endpoints", vpcID, f.Region))
		if missingS3 {
			blocks = append(blocks, fmt.Sprintf(`resource "aws_vpc_endpoint" "s3_%s" {
  vpc_id       = "%s"
  service_name = "com.amazonaws.%s.s3"
  route_table_ids = [] # attach your private route tables
}`, sanitize(vpcID), EscapeHclString(vpcID), EscapeHclString(f.Region)))
		}
		if missingDdb {
			blocks = append(blocks, fmt.Sprintf(`resource "aws_vpc_endpoint" "dynamodb_%s" {
  vpc_id       = "%s"
  service_name = "com.amazonaws.%s.dynamodb"
  route_table_ids = []
}`, sanitize(vpcID), EscapeHclString(vpcID), EscapeHclString(f.Region)))
		}
		blocks = append(blocks, "")
	}
	for _, f := range findings {
		if f.Kind != "logs_infinite_retention" {
			continue
		}
		name := fmt.Sprint(f.Evidence["logGroupName"])
		blocks = append(blocks, fmt.Sprintf(`resource "aws_cloudwatch_log_group" "%s" {
  name              = "%s"
  retention_in_days = %d
}`, sanitize(name), EscapeHclString(name), defaultLogRetentionDays))
		blocks = append(blocks, "")
	}
	for _, f := range findings {
		if f.Kind != "ebs_gp2" {
			continue
		}
		vol := fmt.Sprint(f.Evidence["volumeId"])
		size := f.Evidence["sizeGiB"]
		blocks = append(blocks, fmt.Sprintf(`resource "aws_ebs_volume" "gp3_%s" {
  # Replace in-place: stop instance, snapshot, recreate as gp3, reattach
  availability_zone = "REPLACE_ME"
  size              = %v
  type              = "gp3"
}`, sanitize(vol), size))
		blocks = append(blocks, "")
	}
	for _, f := range findings {
		if f.Kind == "ebs_available" {
			blocks = append(blocks, fmt.Sprintf("# Orphan volume %v — snapshot then delete if unused", f.Evidence["volumeId"]))
			blocks = append(blocks, "")
		}
	}
	for _, f := range findings {
		if f.Kind == "eip_unassociated" {
			blocks = append(blocks, fmt.Sprintf("# Release idle EIP %v (%v)", f.Evidence["allocationId"], f.Evidence["publicIp"]))
			blocks = append(blocks, "")
		}
	}
	for _, f := range findings {
		if f.Kind == "snapshot_stale" {
			blocks = append(blocks, fmt.Sprintf("# Stale snapshot %v — archive or delete after verify", f.Evidence["snapshotId"]))
			blocks = append(blocks, "")
		}
	}
	out := strings.Join(blocks, "\n")
	out = strings.TrimRight(out, "\n") + "\n"
	return out
}

func generateCLIPatch(findings []scan.Finding) string {
	lines := []string{"#!/usr/bin/env bash", "set -euo pipefail", ""}
	for _, f := range findings {
		switch f.Kind {
		case "nat_missing_endpoints":
			lines = append(lines, fmt.Sprintf("# aws ec2 create-vpc-endpoint --vpc-id %v --service-name com.amazonaws.%s.s3", f.Evidence["vpcId"], f.Region))
			lines = append(lines, fmt.Sprintf("# aws ec2 create-vpc-endpoint --vpc-id %v --service-name com.amazonaws.%s.dynamodb", f.Evidence["vpcId"], f.Region))
		case "logs_infinite_retention":
			lines = append(lines, fmt.Sprintf("aws logs put-retention-policy --log-group-name \"%v\" --retention-in-days %d", f.Evidence["logGroupName"], defaultLogRetentionDays))
		case "ebs_gp2":
			lines = append(lines, fmt.Sprintf("# migrate %v gp2 -> gp3 via console or modify-volume", f.Evidence["volumeId"]))
		case "eip_unassociated":
			lines = append(lines, fmt.Sprintf("aws ec2 release-address --allocation-id %v", f.Evidence["allocationId"]))
		default:
			lines = append(lines, fmt.Sprintf("# review finding %s", f.ID))
		}
	}
	return strings.Join(lines, "\n") + "\n"
}

func sanitize(id string) string {
	out := strings.Map(func(r rune) rune {
		if (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || (r >= '0' && r <= '9') || r == '_' {
			return r
		}
		return '_'
	}, id)
	if len(out) > 0 && out[0] >= '0' && out[0] <= '9' {
		out = "_" + out
	}
	return out
}
